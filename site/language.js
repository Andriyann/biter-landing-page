function translate(text) {
  return document.documentElement.lang === 'en' ? englishCopy[text] || text : text;
}

// Record static text before the app renders reviews and simulation controls.
const localizePage = [];
const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  const original = node.nodeValue;
  if (Object.hasOwn(englishCopy, original.trim())) {
    localizePage.push(() => { node.nodeValue = original.replace(original.trim(), () => translate(original.trim())); });
  }
}
for (const el of document.querySelectorAll('[aria-label], [alt], [title], [placeholder], meta[name="description"]')) {
  for (const attr of ['aria-label', 'alt', 'title', 'placeholder', 'content']) {
    const original = el.getAttribute(attr);
    if (Object.hasOwn(englishCopy, original)) localizePage.push(() => el.setAttribute(attr, translate(original)));
  }
}

const languageSwitch = document.getElementById('language-switch');
function applyLanguage(lang) {
  document.documentElement.lang = lang;
  for (const update of localizePage) update();
  languageSwitch.textContent = lang === 'id' ? 'EN' : 'ID';
  languageSwitch.lang = lang === 'id' ? 'en' : 'id';
  languageSwitch.title = lang === 'id' ? 'Switch to English' : 'Ganti ke Bahasa Indonesia';
  languageSwitch.setAttribute('aria-label', languageSwitch.title);
  document.dispatchEvent(new Event('biter-language'));
}
let initialLanguage = 'id';
try { if (localStorage.getItem('biter-language') === 'en') initialLanguage = 'en'; } catch {}
applyLanguage(initialLanguage);
languageSwitch.addEventListener('click', () => {
  const lang = document.documentElement.lang === 'id' ? 'en' : 'id';
  applyLanguage(lang);
  try { localStorage.setItem('biter-language', lang); } catch {}
});
